"""Plot training histories and ROC comparison image.

Generates:
 - `outputs/training_comparison.png` (4-panel: softmax loss/acc, metric loss/acc)
 - If ROC image found at `outputs/roc_comparison.png`, prints path (it may be regenerated by `scripts/evaluate.py`).

Usage:
    python scripts/plot_results.py

Optional args:
    --softmax-history PATH
    --metric-history PATH
    --roc-image PATH
    --out-dir PATH
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Dict, List

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd


def load_history(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"History file not found: {path}")
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    # Expecting list of dicts with epoch, train_loss, train_acc, val_loss, val_acc
    return pd.DataFrame(data)


def plot_training(soft_df: pd.DataFrame, metric_df: pd.DataFrame, out_path: Path) -> None:
    sns.set(style='whitegrid')
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))

    # Softmax Loss
    ax = axes[0, 0]
    ax.plot(soft_df['epoch'], soft_df['train_loss'], label='Train Loss')
    ax.plot(soft_df['epoch'], soft_df['val_loss'], label='Validation Loss')
    ax.set_title('Softmax (Classification) Model Loss')
    ax.set_xlabel('Epoch')
    ax.set_ylabel('Cross-Entropy Loss')
    ax.legend()

    # Softmax Accuracy
    ax = axes[0, 1]
    ax.plot(soft_df['epoch'], soft_df['train_acc'], label='Train Accuracy')
    ax.plot(soft_df['epoch'], soft_df['val_acc'], label='Validation Accuracy')
    ax.set_title('Softmax (Classification) Model Accuracy')
    ax.set_xlabel('Epoch')
    ax.set_ylabel('Accuracy')
    ax.legend()

    # Metric Loss (Triplet)
    ax = axes[1, 0]
    ax.plot(metric_df['epoch'], metric_df['train_loss'], label='Train Loss')
    ax.plot(metric_df['epoch'], metric_df['val_loss'], label='Validation Loss')
    ax.set_title('Metric (Triplet) Model Loss')
    ax.set_xlabel('Epoch')
    ax.set_ylabel('Triplet Loss')
    ax.legend()

    # Metric Accuracy
    ax = axes[1, 1]
    ax.plot(metric_df['epoch'], metric_df['train_acc'], label='Train Accuracy (Pos < Neg)')
    ax.plot(metric_df['epoch'], metric_df['val_acc'], label='Validation Accuracy (Pos < Neg)')
    ax.set_title('Metric (Triplet) Model Accuracy')
    ax.set_xlabel('Epoch')
    ax.set_ylabel('Accuracy')
    ax.legend()

    fig.suptitle('Model Training Comparison', fontsize=16)
    plt.tight_layout(rect=[0, 0.03, 1, 0.97])
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=200)
    plt.close(fig)
    print(f"Saved training comparison plot: {out_path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--softmax-history', type=Path, default=Path('outputs/softmax_training_history.json'))
    parser.add_argument('--metric-history', type=Path, default=Path('outputs/metric_training_history.json'))
    parser.add_argument('--roc-image', type=Path, default=Path('outputs/roc_comparison.png'))
    parser.add_argument('--out-dir', type=Path, default=Path('outputs'))
    args = parser.parse_args()

    try:
        soft_df = load_history(args.softmax_history)
    except Exception as e:
        print(f"Could not load softmax history: {e}")
        soft_df = None

    try:
        metric_df = load_history(args.metric_history)
    except Exception as e:
        print(f"Could not load metric history: {e}")
        metric_df = None

    if soft_df is None and metric_df is None:
        print('No training histories available. Exiting.')
        return

    # If one of them is missing, create a dummy empty DataFrame with expected columns to avoid plotting errors
    if soft_df is None:
        soft_df = pd.DataFrame({'epoch': [], 'train_loss': [], 'val_loss': [], 'train_acc': [], 'val_acc': []})
    if metric_df is None:
        metric_df = pd.DataFrame({'epoch': [], 'train_loss': [], 'val_loss': [], 'train_acc': [], 'val_acc': []})

    out_path = args.out_dir / 'training_comparison.png'
    plot_training(soft_df, metric_df, out_path)

    if args.roc_image.exists():
        print(f"ROC image found at: {args.roc_image}")
    else:
        print(f"ROC image not found at {args.roc_image}. Run `python scripts/evaluate.py` to generate it.")


if __name__ == '__main__':
    main()
